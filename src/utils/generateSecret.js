// Импортируем встроенный модуль Node.js для криптографических операций
import crypto from "crypto";

// Функция для генерации секретного ключа 
export default function generateSecret(name) {
    // Проверяем, запущено ли приложение в production-режиме
    if (process.env.NODE_ENV === "production") {
        // В продакшене нельзя генерировать секреты на лету — они должны быть в переменных окружения
        // Выбрасываем ошибку, чтобы предотвратить небезопасную работу приложения
        throw new Error(`${name} должен быть установлен в переменных окружения в режиме production`);
    }

    // Генерируем криптостойкий случайный секрет
    // - randomBytes(64) создает 64 байта случайных данных
    // - toString("hex") преобразует байты в шестнадцатеричную строку
    const generated = crypto.randomBytes(64).toString("hex");
    
    // Выводим предупреждение в консоль (только для разработки)
    console.warn(`[config] ${name} не установлен, используем сгенерированный секрет (только для разработки):`, generated);
    
    // Возвращаем сгенерированный секрет для использования в приложении
    return generated;
}