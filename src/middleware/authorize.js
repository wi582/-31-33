// Импортируем класс операционных ошибок для возврата ошибки доступа
import AppError from "../utils/appError.js";

// Фабрика middleware для авторизации по ролям
// Использует rest параметр (...roles) — принимает любое количество аргументов
// Пример: authorize('admin', 'moderator')
const authorize = (...roles) => {
    // Возвращаем middleware-функцию, которая имеет доступ к req, res, next
    return (req, res, next) => {
        // Проверяем, входит ли роль текущего пользователя в список разрешённых
        // req.user предварительно должен быть установлен middleware аутентификации
        if (!roles.includes(req.user.role)) {
            // Если роль не подходит — возвращаем ошибку 403 (Forbidden)
            return next(
                new AppError("У вас нет прав для доступа к этому ресурсу", 403),
            );
        }
        // Если роль разрешена — пропускаем запрос дальше
        next();
    };
};

// Экспортируем функцию авторизации по умолчанию
export default authorize;